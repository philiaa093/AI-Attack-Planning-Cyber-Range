"""Audit-first gate remediation; preserve evidence, never 'repair' stored hashes.

Default CLI audit requires the three historical evaluation runs recorded in the
handoff. --apply can quarantine only verified generated bytecode. Format/schema
errors are reported for source repair; they never authorize editing evidence.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path

from runtime.evaluation.usage_costs import LIMIT, canonical, no_links, read_verified, sha, utc_now


HISTORICAL_RUNS = (
    "RUN-EVAL-28f2ce10b1e24f0c867f3980e0212c5a",
    "RUN-EVAL-2c8fc0463d9144419e2de854d5e76d84",
    "RUN-EVAL-db2d8184ca0449abb358a3f7646f91cb",
)
_RUN = re.compile(r"RUN-EVAL-[0-9a-f]{32}")
_CACHE = re.compile(r"(.+)\.cpython-\d{2,3}(?:\.opt-[12])?\.pyc")
_SAFE_ROOTS = {"agent", "runtime", "dashboards", "scripts", "tests", "tools", "evaluation"}
# ponytail: one user-approved incident only; new incidents require separate review.
UI_CACHE_MANIFEST = "runtime/gate-hygiene/UI-CHECK-d0076efaab1b4a1bbf5acb772ea8be3a/bytecode-preservation.json"
UI_CACHE_MANIFEST_SHA256 = "7d5f23e4826b966282283ebcbf05174a46bb70d1ea9e299704bceb3a0153df84"


def confined(root, relative):
    if type(relative) is not str or "\\" in relative:
        raise ValueError("POSIX relative gate path required")
    candidate = Path(relative)
    if candidate.is_absolute() or any(part in ("..", "") for part in candidate.parts):
        raise ValueError("gate path escaped repository")
    path = root / candidate
    no_links(path)
    if not path.resolve().is_relative_to(root.resolve()):
        raise ValueError("gate path escaped repository")
    return path


def parse_gate_errors(output):
    if type(output) is not str or len(output.encode()) > LIMIT:
        raise ValueError("bounded gate output required")
    return tuple(dict.fromkeys(line[2:] for line in output.splitlines() if line.startswith("- ")))


def verify_historical_runs(root, required_runs=HISTORICAL_RUNS, *, historical_root=None):
    """Missing run or digest mismatch blocks cleanup; source hashes are historical.

    Partial runs have no completion manifest and remain explicitly UNRESOLVED.
    No new manifest is manufactured and no stored digest is changed.
    """
    if not required_runs or any(type(r) is not str or not _RUN.fullmatch(r) for r in required_runs):
        raise ValueError("explicit nonempty historical run inventory required")
    root = Path(root).absolute()
    base = root / "runtime/evaluation-runs" if historical_root is None else Path(historical_root).absolute()
    no_links(base)
    if base not in (root / "runtime/evaluation-runs", root / "evidence/runtime"):
        raise ValueError("explicit historical root must be runtime/evaluation-runs or evidence/runtime")
    failures, receipts = [], []
    for run_id in required_runs:
        directory = confined(root, (base / run_id).relative_to(root).as_posix())
        if not directory.is_dir():
            failures.append(dict(run_id=run_id, reason="MISSING_HISTORICAL_EVIDENCE"))
            continue
        manifest = directory / "manifest.json"
        if not manifest.exists():
            expected = {"configuration.json", "validation-synthetic-review.log.json",
                        "validation-synthetic-review.metrics.json", "validation-synthetic-random.log.json"}
            actual = {p.name for p in directory.iterdir() if p.is_file()}
            if run_id == HISTORICAL_RUNS[0] and expected <= actual:
                receipts.append(dict(run_id=run_id, integrity_state="PARTIAL_UNRESOLVED"))
            else:
                failures.append(dict(run_id=run_id, reason="MISSING_COMPLETION_MANIFEST"))
            continue
        try:
            no_links(manifest)
            raw = manifest.read_bytes()
            if len(raw) > LIMIT:
                raise ValueError("manifest too large")
            document = read_verified(manifest, sha(raw))
            if document["run_id"] != run_id:
                raise ValueError("run identity mismatch")
            refs = document["observed_state"]["artifacts"]
            if type(refs) is not list or not 1 <= len(refs) <= 100_000:
                raise ValueError("bounded artifact refs required")
            names = set()
            for ref in refs:
                if (type(ref) is not dict or set(ref) != {"name", "sha256"}
                        or type(ref["name"]) is not str or not re.fullmatch(r"[a-zA-Z0-9][a-zA-Z0-9_.-]{0,127}", ref["name"])
                        or ".." in ref["name"] or ref["name"] in names):
                    raise ValueError("malformed/conflicting artifact reference")
                names.add(ref["name"])
                path = confined(root, (directory / ref["name"]).relative_to(root).as_posix())
                data = path.read_bytes()
                if len(data) > LIMIT or sha(data) != ref["sha256"]:
                    raise ValueError("historical artifact hash mismatch")
            actual = {p.name for p in directory.iterdir()}
            if actual != names | {"manifest.json"}:
                raise ValueError("unlisted/missing historical artifact")
            receipts.append(dict(run_id=run_id, integrity_state="HASHES_MATCH",
                                 manifest_sha256=sha(raw), artifacts=len(refs)))
        except (ValueError, OSError, KeyError, TypeError):
            failures.append(dict(run_id=run_id, reason="HISTORICAL_INTEGRITY_UNRESOLVED"))
    return receipts, failures


def make_plan(root, gate_output, required_runs=HISTORICAL_RUNS, *, historical_root=None):
    root = Path(root).absolute()
    no_links(root)
    integrity, failures = verify_historical_runs(root, required_runs, historical_root=historical_root)
    errors = parse_gate_errors(gate_output)
    actions, source_repairs = [], []
    for error in errors:
        if error.startswith("forbidden artifact "):
            relative = error.removeprefix("forbidden artifact ")
            path = confined(root, relative)
            match = _CACHE.fullmatch(path.name)
            if (not match or path.parent.name != "__pycache__" or Path(relative).parts[0] not in _SAFE_ROOTS
                    or not (path.parent.parent / (match[1] + ".py")).is_file()):
                source_repairs.append(dict(error=error, repair="MANUAL_NONCACHE_ARTIFACT_REVIEW"))
                continue
            raw = path.read_bytes()
            if len(raw) > LIMIT or len(raw) < 16 or raw[:4] != importlib.util.MAGIC_NUMBER:
                source_repairs.append(dict(error=error, repair="UNRECOGNIZED_BYTECODE_PRESERVE"))
                continue
            actions.append(dict(relative_path=relative, preimage_sha256=sha(raw), size=len(raw),
                                operation="QUARANTINE_GENERATED_BYTECODE"))
        else:
            repair = "REVIEW_SOURCE_OR_SCHEMA; PRESERVE_EVIDENCE"
            if error.startswith(".demo-session.json:"):
                repair = "VALIDATE_SESSION_LIFECYCLE_SCHEMA; KEEP_ACTIVE_SESSION_FILE"
            elif "/analysis.json: invalid status" in error:
                repair = "VALIDATE_LEGACY_STATISTICAL_RECEIPT_ROLE; KEEP_RECORDED_BYTES"
            elif "/report.md: external URL" in error:
                repair = "REGISTER_AND_VALIDATE_REPORT_CITATION; KEEP_RECORDED_BYTES"
            source_repairs.append(dict(error=error, repair=repair))
    return dict(schema_version=1, created_at_utc=utc_now(), source="REPOSITORY_GATE_AUDIT",
                redaction="METADATA_ONLY", integrity_receipts=integrity, evidence_failures=failures,
                required_runs=list(required_runs),
                historical_root=str(root / "runtime/evaluation-runs" if historical_root is None else Path(historical_root).absolute()),
                gate_errors=list(errors), proposed_cache_actions=actions, source_repairs=source_repairs,
                cleanup_state="BLOCKED_MISSING_EVIDENCE" if failures else "REVIEWABLE_PLAN")


def _verify_ui_cache_exception(root, plan):
    expected = [dict(run_id=r, reason="MISSING_HISTORICAL_EVIDENCE") for r in HISTORICAL_RUNS]
    if plan["required_runs"] != list(HISTORICAL_RUNS) or plan["evidence_failures"] != expected:
        raise ValueError("exception covers only the three missing historical runs")
    for base in ("runtime/evaluation-runs", "evidence/runtime"):
        for run in HISTORICAL_RUNS:
            if confined(root, base + "/" + run).exists():
                raise ValueError("historical entry now exists; fresh review required")
    manifest = confined(root, UI_CACHE_MANIFEST)
    raw = manifest.read_bytes()
    if sha(raw) != UI_CACHE_MANIFEST_SHA256:
        raise ValueError("approved preservation manifest changed")
    files = json.loads(raw)["files"]
    if len(files) != 28 or len({f["source_path"] for f in files}) != 28:
        raise ValueError("exact 28-file preservation inventory required")
    expected_actions = []
    for entry in files:
        copy = confined(root, (manifest.parent / entry["copy_path"]).relative_to(root).as_posix())
        if not copy.is_relative_to(manifest.parent / "bytecode-copies"):
            raise ValueError("preserved copy outside approved directory")
        data = copy.read_bytes()
        if len(data) != entry["bytes"] or sha(data) != entry["sha256"]:
            raise ValueError("preserved copy changed")
        expected_actions.append(dict(relative_path=entry["source_path"], preimage_sha256=entry["sha256"],
                                     size=entry["bytes"], operation="QUARANTINE_GENERATED_BYTECODE"))
    if sorted(plan["proposed_cache_actions"], key=lambda a: a["relative_path"]) != sorted(expected_actions, key=lambda a: a["relative_path"]):
        raise ValueError("exception requires exact approved cache paths and hashes")
    return dict(source="EXPLICIT_USER_APPROVAL_2026_10_14", historical_evidence="MISSING_UNVERIFIABLE",
                scope="ONLY_28_PINNED_BYTECODE_FILES", manifest=UI_CACHE_MANIFEST,
                manifest_sha256=UI_CACHE_MANIFEST_SHA256, task_promotion=False)


def apply_cache_plan(root, plan, archive_parent, *, approved_ui_cache_exception=False):
    """Copy+fsync+verify before unlink; no recursive deletion, no hash rewriting.

    Requires a quiescent, trusted single-writer workspace. Any observed change
    aborts and leaves archival copies/partial receipts available for inspection.
    """
    import os
    import uuid
    root = Path(root).absolute()
    no_links(root)
    if plan["evidence_failures"] and not approved_ui_cache_exception:
        raise ValueError("historical evidence missing/corrupt; cleanup prohibited")
    _, failures = verify_historical_runs(root, tuple(plan["required_runs"]), historical_root=plan["historical_root"])
    if approved_ui_cache_exception:
        if failures != plan["evidence_failures"]:
            raise ValueError("historical evidence changed since audit")
        disposition = _verify_ui_cache_exception(root, plan)
        plan = dict(plan, exception_disposition=disposition)
    elif failures:
        raise ValueError("historical evidence changed since audit; cleanup prohibited")
    # Revalidate disposable-file scope even when called with a forged plan.
    for action in plan["proposed_cache_actions"]:
        if type(action) is not dict or set(action) != {"relative_path", "preimage_sha256", "size", "operation"}:
            raise ValueError("closed cache action required")
        path = confined(root, action["relative_path"])
        match = _CACHE.fullmatch(path.name)
        if (action["operation"] != "QUARANTINE_GENERATED_BYTECODE" or not match
                or path.parent.name != "__pycache__" or Path(action["relative_path"]).parts[0] not in _SAFE_ROOTS
                or not (path.parent.parent / (match[1] + ".py")).is_file()
                or type(action["preimage_sha256"]) is not str
                or not re.fullmatch(r"[0-9a-f]{64}", action["preimage_sha256"])):
            raise ValueError("only generated cache files may be quarantined")
        raw = path.read_bytes()
        if len(raw) > LIMIT or len(raw) < 16 or raw[:4] != importlib.util.MAGIC_NUMBER or sha(raw) != action["preimage_sha256"]:
            raise ValueError("cache preimage changed or is not recognized bytecode")
    parent = Path(archive_parent).absolute()
    no_links(parent)
    if not parent.resolve().is_relative_to((root / "runtime/gate-remediation").resolve()):
        raise ValueError("archive must stay within runtime/gate-remediation")
    parent.mkdir(parents=True, exist_ok=True)
    directory = parent / ("CLEANUP-" + uuid.uuid4().hex)
    directory.mkdir(exist_ok=False)
    plan_path = directory / "plan.json"
    with plan_path.open("xb") as stream:
        stream.write(canonical(plan)); stream.flush(); os.fsync(stream.fileno())
    for index, action in enumerate(plan["proposed_cache_actions"]):
        path = confined(root, action["relative_path"])
        raw = path.read_bytes()
        if sha(raw) != action["preimage_sha256"]:
            raise ValueError("bytecode changed since audit; cleanup stopped")
        archive = directory / (f"cache-{index:04d}-" + action["preimage_sha256"] + ".archive")
        with archive.open("xb") as stream:
            stream.write(raw); stream.flush(); os.fsync(stream.fileno())
        if sha(archive.read_bytes()) != action["preimage_sha256"]:
            raise ValueError("archive verification failed; original preserved")
        # Recheck immediately before targeted unlink; caller must stop concurrent writers.
        no_links(path)
        if sha(path.read_bytes()) != action["preimage_sha256"]:
            raise ValueError("bytecode replaced during archival; original preserved")
        path.unlink()
        receipt = dict(source=action["relative_path"], archive=archive.name,
                       sha256=action["preimage_sha256"], created_at_utc=utc_now(),
                       observed_state="ARCHIVED_GENERATED_CACHE")
        with (directory / f"receipt-{index:04d}.json").open("xb") as stream:
            stream.write(canonical(receipt)); stream.flush(); os.fsync(stream.fileno())
    return directory


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--approved-ui-cache-exception", action="store_true",
                        help="apply only the user-approved, hash-pinned 28-cache incident exception")
    parser.add_argument("--gate-output", type=Path, help="saved gate output; otherwise run the fixed local validator")
    parser.add_argument("--historical-root", type=Path, help="explicit restored root: evidence/runtime or runtime/evaluation-runs")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    if args.gate_output:
        no_links(args.gate_output.absolute())
        raw = args.gate_output.read_bytes()
        if len(raw) > LIMIT:
            parser.error("gate output too large")
        output = raw.decode("utf-8")
    else:
        result = subprocess.run([sys.executable, "-B", str(root / "scripts/validation/validate_scaffold.py")],
                                cwd=root, capture_output=True, text=True, timeout=60, check=False)
        if result.returncode not in (0, 1) or (result.returncode == 1 and "SCAFFOLD INVALID" not in result.stdout):
            parser.exit(2, "Validator failed unexpectedly; no cleanup performed.\n")
        output = result.stdout
    plan = make_plan(root, output, historical_root=args.historical_root)
    print(json.dumps(plan, indent=2, ensure_ascii=True))
    if args.approved_ui_cache_exception and not args.apply:
        parser.error("incident exception requires --apply")
    if plan["evidence_failures"] and not args.approved_ui_cache_exception:
        parser.exit(2, "Historical evidence is missing/corrupt; no cleanup performed.\n")
    if args.apply:
        directory = apply_cache_plan(root, plan, root / "runtime/gate-remediation",
                                     approved_ui_cache_exception=args.approved_ui_cache_exception)
        print(f"Verified cache archive: {directory}")
        result = subprocess.run([sys.executable, "-B", str(root / "scripts/validation/validate_scaffold.py")],
                                cwd=root, capture_output=True, text=True, timeout=60, check=False)
        print(result.stdout)
        if result.returncode != 0:
            parser.exit(1, "Repository gate still fails; source/schema repair required.\n")
    elif plan["gate_errors"]:
        parser.exit(1, "Audit only; gate errors remain and no files were changed.\n")


if __name__ == "__main__":
    main()
