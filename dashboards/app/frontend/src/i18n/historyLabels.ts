/** Unknown source text is retained verbatim; it must not become an invented claim. */
export function historyLabel(lang: Language, value: string): string {
  if (lang !== 'vi') return value;
  const key = Object.prototype.hasOwnProperty.call(vi, value)
    ? value : value.toUpperCase().replace(/ /g, '_');
  const direct = Object.prototype.hasOwnProperty.call(vi, key) ? vi[key] : undefined;
  if (direct) return direct;
  const patterns: [RegExp, (...parts: string[]) => string][] = [
    [/^Run initialized in (.+) mode\.$/, (mode) => `Lượt chạy khởi tạo ở chế độ ${historyLabel(lang, mode)}.`],
    [/^Planner proposed (.+) \((.+)\)\.$/, (action, mode) => `Bộ lập kế hoạch đề xuất ${action} (${historyLabel(lang, mode)}).`],
    [/^Safety Gate denied proposal: (.+)\.$/, (reason) => `Cổng an toàn từ chối đề xuất: ${historyLabel(lang, reason)}.`],
    [/^Cryptographic evidence persisted \((.+)\)\.$/, (id) => `Đã lưu bằng chứng mật mã (${id}).`],
    [/^Execution completed cleanly\. Reason: (.+)\.$/, (reason) => `Thực thi kết thúc bình thường. Lý do: ${historyLabel(lang, reason)}.`],
    [/^Execution step (.+) logged\.$/, (step) => `Đã ghi bước thực thi ${historyLabel(lang, step)}.`],
    [/^Recorded descriptive comparison between (.+) \((.+), (.+)\) and (.+) \((.+), (.+)\)\. Reported network dispatches: (.+) vs (.+)\. Recorded safety enforcement: (.+) refusals vs (.+) refusals\.$/,
      (a, ap, am, b, bp, bm, ad, bd, ar, br) => `Đối chiếu mô tả đã ghi nhận giữa ${a} (${historyLabel(lang, ap)}, ${historyLabel(lang, am)}) và ${b} (${historyLabel(lang, bp)}, ${historyLabel(lang, bm)}). Lượt gửi yêu cầu mạng được báo cáo: ${ad === 'None' ? 'chưa ghi nhận' : ad} so với ${bd === 'None' ? 'chưa ghi nhận' : bd}. Số lượt từ chối đã ghi nhận: ${ar === 'None' ? 'chưa ghi nhận' : ar} so với ${br === 'None' ? 'chưa ghi nhận' : br}.`],
  ];
  for (const [pattern, translate] of patterns) {
    const match = value.match(pattern);
    if (match) return translate(...match.slice(1));
  }
  const sharedLabel = displayValue(value, lang);
  return typeof sharedLabel === 'string' ? sharedLabel : value;
}
